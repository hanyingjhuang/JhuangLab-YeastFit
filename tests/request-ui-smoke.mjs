import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const base=process.env.YEASTFIT_URL||'http://127.0.0.1:4173';
const browser=await chromium.launch({headless:true});
const errors=[];
const context=await browser.newContext({viewport:{width:1440,height:900}});
const page=await context.newPage();
page.on('pageerror',e=>errors.push(`pageerror: ${e.message}`));
page.on('console',m=>{if(m.type()==='error')errors.push(`console: ${m.text()}`)});
await page.goto(base,{waitUntil:'networkidle'});
await page.waitForFunction(()=>window.YeastFitWorkflowV05);
assert.equal(await page.locator('#requestBtn').count(),1,'request button must exist');
assert.equal(await page.locator('#demoBtn').count(),0,'redundant top demo button stays removed');
await page.evaluate(()=>{window.__requestUrl='';window.open=u=>{window.__requestUrl=String(u);return null}});
await page.locator('#requestBtn').click();
assert.equal(await page.locator('#requestDialog').evaluate(el=>el.open),true,'request dialog opens');
assert.equal(await page.locator('#requestArea').inputValue(),'Setup','request area defaults to current workflow section');
await page.locator('#requestType').selectOption({label:'Theme color'});
await page.locator('#requestSummary').fill('Use a darker primary green');
await page.locator('#requestDetails').fill('Keep contrast high and preserve the existing palette structure.');
await page.locator('#openRequestBtn').click();
const url=await page.evaluate(()=>window.__requestUrl);
assert.match(url,/github\.com\/hanyingjhuang\/JhuangLab-YeastFit\/issues\/new\?/);
const parsed=new URL(url);
assert.equal(parsed.searchParams.get('template'),'change-request.yml');
assert.equal(parsed.searchParams.get('request_type'),'Theme color');
assert.equal(parsed.searchParams.get('area'),'Setup');
assert.equal(parsed.searchParams.get('summary'),'Use a darker primary green');
assert.equal(await page.locator('#requestDialog').evaluate(el=>el.open),false,'dialog closes after continuing');
assert.deepEqual(errors,[],`browser errors: ${errors.join(' | ')}`);
await context.close();

const mobile=await browser.newContext({viewport:{width:390,height:844}});
const mpage=await mobile.newPage();
await mpage.goto(base,{waitUntil:'networkidle'});await mpage.waitForFunction(()=>window.YeastFitWorkflowV05);
assert.equal(await mpage.locator('#requestBtn').count(),1,'request button remains available on mobile');
const overflow=await mpage.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth);
assert.ok(overflow<=6,`request entry introduces ${overflow}px mobile overflow`);
await mobile.close();await browser.close();
console.log('Request UI validation passed on desktop and mobile.');
