import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const base=process.env.YEASTFIT_URL||'http://127.0.0.1:4173';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1280,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.goto(base,{waitUntil:'networkidle'});
await page.waitForFunction(()=>window.YeastFit&&window.YeastFitPresets&&document.querySelector('#dataQualityManager'));
await page.evaluate(()=>window.YeastFitPresets.loadDemo('endpoint'));
await page.waitForFunction(()=>window.YeastFit?.S?.design?.preset==='endpoint'&&window.YeastFit.S.metrics?.length>0);
await page.evaluate(()=>window.YeastFit.step(3));
await page.waitForTimeout(150);
const target=page.locator('#dqTarget option').filter({hasNotText:'Choose a sample or well'}).first();
assert.ok(await target.count(),'quality manager must list a sample or well');
const value=await target.getAttribute('value');
await page.locator('#dqTarget').selectOption(value);
await page.locator('#dqContaminate').click();
assert.equal(await page.evaluate(()=>window.YeastFit.S.qualityExclusions.length),1);
assert.match(await page.locator('#dataQualityManager').innerText(),/CONTAMINATED/);
const rec=await page.evaluate(()=>window.YeastFit.S.qualityExclusions[0]);
assert.ok((await page.locator('#excludedIds').inputValue()).includes(rec.key));
await page.locator('#runAnalysisBtn').click();
await page.waitForFunction(()=>window.YeastFit.S.metrics?.length>0);
const stillPresent=await page.evaluate(r=>window.YeastFit.S.metrics.some(x=>String(x[r.scope]??x.sample??x.well??'')===r.key),rec);
assert.equal(stillPresent,false,'contaminated unit must be excluded from analysis');
await page.evaluate(()=>window.YeastFit.step(3));
await page.locator('[data-dq-restore="0"]').click();
assert.equal(await page.evaluate(()=>window.YeastFit.S.qualityExclusions.length),0);

await page.evaluate(()=>window.YeastFit.step(1));
await page.locator('.paste-box').evaluate(el=>el.open=true);
await page.locator('#pasteArea').fill('value,sample,genotype,role,biological_rep\n1.0,WT1,WT,control,1\n,WT2,WT,control,2\n1.1,WT3,WT,control,3\n0.5,M1,mut,sample,1\n0.6,M2,mut,sample,2\n0.55,M3,mut,sample,3');
await page.locator('#parsePasteBtn').click();
await page.waitForFunction(()=>window.YeastFit.S.raw.length===6);
await page.evaluate(()=>window.YeastFit.step(3));
await page.waitForTimeout(150);
assert.match(await page.locator('#dataQualityManager').innerText(),/1 of 6 measurements missing/);
assert.deepEqual(errors,[]);
await browser.close();
console.log('Data-quality UI validation passed.');
